/**
 ******************************************************************************
 * @file    render.h
 * @brief   把游戏画到 LCD 上（唯一一个碰 LCD_* API 的模块）
 *
 * 刷新策略（对应任务书"尽可能局部刷新，避免闪烁"）：
 *   Render_Begin  整屏重画一次：背景 + 墙 + 红区 + 目标 + 状态栏 + 按钮
 *   Render_Frame  每帧只擦旧球、补画被擦到的静态元素、画新球
 *
 * 所以稳定运行时每帧的写入量 ≈ 一个圆（约 300 像素），不是 38 万像素。
 ******************************************************************************
 */
#ifndef __RENDER_H
#define __RENDER_H

#include "app.h"

/* 整屏重画（关卡切换、状态变化时调用） */
void Render_Begin(App_Ctx *a);

/* 每帧局部刷新（只动球） */
void Render_Frame(App_Ctx *a);

#endif /* __RENDER_H */
