/**
 ******************************************************************************
 * @file    fmt.h
 * @brief   坐标格式化（纯 C，可 PC 单测）
 *
 * 两种格式：
 *   Fmt_E7   十进制度   "31.8451022"
 *   Fmt_Dms  度分秒     "31d50'42.3\"N"
 *
 * 为什么单独拆出来：
 *   度分秒换算是最容易算错的一类代码（° ' " 三级 ×60，还要四舍五入），
 *   放在 main.c 里就没法单测。拆成纯 C 之后可以用 gcc 直接验证。
 *
 * ⚠️ 不要在这里用度数符号（U+00B0）。它是非 ASCII，UTF-8 下是两个字节，
 *    ARMCC 按 GBK 读源文件时会把后半个字节和引号拼成一个汉字，
 *    直接报 "missing closing quote"。所以用 'd' 代替。
 ******************************************************************************
 */
#ifndef __FMT_H
#define __FMT_H

#include <stdint.h>

/** ×1e7 定点度 -> 十进制度字符串，例如 318451022 -> "31.8451022" */
void Fmt_E7(char *buf, int n, int32_t e7);

/** ×1e7 定点度 -> 度分秒字符串，例如 318451022 -> "31d50'42.3\"N"
 *  @param pos  正方向字符（纬度 'N'、经度 'E'）
 *  @param neg  负方向字符（纬度 'S'、经度 'W'）
 */
void Fmt_Dms(char *buf, int n, int32_t e7, char pos, char neg);

#endif /* __FMT_H */
