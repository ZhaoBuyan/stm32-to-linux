/**
 * list_demo.c —— 单链表：最小可运行例子
 *
 * 先用最笨的办法（手工连 2 个节点），看清链表到底是什么样子。
 * 先预测输出，再运行。
 *
 * 编译：
 *   gcc -std=c11 -Wall -Wextra -o list_demo.exe list_demo.c
 *   .\list_demo.exe
 */
#include <stdio.h>
#include <stdint.h>

/* ============================================================================
 * 节点定义
 *
 *   tag 是 struct Node
 *   别名是 Node
 *
 * 结构体内部只能写 struct Node，因为别名的 typedef 还没生效。
 * ========================================================================== */
typedef struct Node
{
    uint8_t      data;
    struct Node *next;      /* 指向同类型的下一个节点 */
} Node;

int main(void)
{
    /* ------------------------------------------------------------------
     * 第一步：造三个节点（只是三个普通变量）
     * ------------------------------------------------------------------ */
    Node n1, n2, n3;

    n1.data = 10;
    n2.data = 20;
    n3.data = 30;

    /* ------------------------------------------------------------------
     * 第二步：把它们"连起来"
     *
     * 链表的全部秘密就在这三行：让每个节点的 next 指向下一个节点。
     * ------------------------------------------------------------------ */
    n1.next = &n2;          /* n1 的 next 指向 n2 */
    n2.next = &n3;          /* n2 的 next 指向 n3 */
    n3.next = NULL;         /* 最后一个的 next 是 NULL，表示"到头了" */

    /* ------------------------------------------------------------------
     * 第三步：遍历（这就是所有链表操作的原型）
     *
     *   p 从第一个节点出发，跟着 next 一路走，直到 NULL。
     * ------------------------------------------------------------------ */
    {
        Node *p = &n1;      /* p 指向第一个 */

        printf("遍历结果：\n");
        while (p != NULL)
        {
            printf("  节点 data = %u\n", (unsigned)p->data);
            p = p->next;    /* 挪到下一个 —— 注意是 p->next，不是 p++ */
        }
    }

    /* ------------------------------------------------------------------
     * 第四步：验证一下"连起来"到底意味着什么
     * ------------------------------------------------------------------ */
    printf("\n用两种写法访问第二个节点：\n");
    printf("  n2.data        = %u\n", (unsigned)n2.data);
    printf("  n1.next->data  = %u   <-- 和上面一样吗？\n", (unsigned)n1.next->data);

    printf("\n再往下一层：\n");
    printf("  n3.data             = %u\n", (unsigned)n3.data);
    printf("  n1.next->next->data = %u   <-- 和上面一样吗？\n",
           (unsigned)n1.next->next->data);

    printf("\nsizeof(Node) = %u 字节\n", (unsigned)sizeof(Node));
    printf("  1 字节 data + 指针，为什么不是 1 + %u？\n",
           (unsigned)sizeof(void *));

    return 0;
}
