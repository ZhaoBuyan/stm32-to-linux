/**
 * ptr_demo.c —— 指针「怎么用」的三个基本场景
 *
 * 用法：
 *   1. 先【不要运行】，用纸/记事本预测每一行输出
 *   2. 再编译运行，对比预测和实际
 *   3. 哪一条预测错了，那条就是你的漏洞
 *
 * 编译：
 *   gcc -std=c11 -Wall -Wextra -o ptr_demo.exe ptr_demo.c
 *   .\ptr_demo.exe
 */
#include <stdio.h>
#include <stdint.h>

/* ==========================================================================
 * 场景 1：传值 —— 函数里怎么改都影响不到外面
 * ========================================================================== */
void set5_value(uint8_t v)
{
    v = 5;
}

/* ==========================================================================
 * 场景 2：传址 —— 通过地址改外面的变量
 *
 * 对比场景 1，唯一的区别：
 *   参数写成  uint8_t *v   （接地址）
 *   赋值写成  *v = 5       （改那个地址里的东西）
 * ========================================================================== */
void set5_ptr(uint8_t *v)
{
    *v = 5;
}

/* ==========================================================================
 * 场景 3：一个函数交回两个结果
 *
 * 返回值只能带一样东西，另外一样的"出口"就是用指针。
 * 这正是 RB_Get(uint8_t *b) 的写法。
 * ========================================================================== */
void div_mod(uint16_t a, uint16_t b, uint16_t *q, uint16_t *r)
{
    *q = a / b;
    *r = a % b;
}

/* ==========================================================================
 * 场景 4：数组当参数 —— 数组名本身就能当地址传
 * ========================================================================== */
uint16_t sum_arr(const uint8_t *buf, uint16_t len)
{
    uint16_t s = 0;
    uint16_t i;

    for (i = 0; i < len; i++)
    {
        s += buf[i];            /* 用下标访问一个"指针" */
    }
    return s;
}

int main(void)
{
    uint8_t  x;
    uint16_t q, r;
    uint8_t  data[4] = { 10, 20, 30, 40 };

    printf("===== 场景 1：传值 =====\n");
    x = 1;
    set5_value(x);
    printf("x = %u        <-- 预测是多少？\n", (unsigned)x);

    printf("\n===== 场景 2：传址 =====\n");
    x = 1;
    set5_ptr(&x);               /* 注意这里多了 & */
    printf("x = %u        <-- 预测是多少？\n", (unsigned)x);

    printf("\n===== 场景 3：两个出口 =====\n");
    q = 0; r = 0;
    div_mod(17, 5, &q, &r);
    printf("17 / 5 = %u 余 %u   <-- 预测是多少？\n",
           (unsigned)q, (unsigned)r);

    printf("\n===== 场景 4：数组当参数 =====\n");
    printf("sum = %u      <-- 预测是多少？\n",
           (unsigned)sum_arr(data, 4));

    printf("\n===== 场景 5：指针自己也能挪 =====\n");
    {
        const uint8_t *p = data;      /* p 指向 data[0] */
        printf("p[0] = %u\n", (unsigned)p[0]);
        p++;                          /* p 指向 data[1] */
        printf("p[0] = %u\n", (unsigned)p[0]);
        printf("*p   = %u   <-- *p 和 p[0] 是不是同一个东西？\n", (unsigned)*p);
        printf("*(p+1) = %u\n", (unsigned)*(p + 1));
    }

    return 0;
}
