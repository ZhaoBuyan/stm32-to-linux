/**
 ******************************************************************************
 * @file    ringbuf.h
 * @brief   环形缓冲（FIFO）—— 中断与主循环之间的"排队区"
 *
 * ★ 设计要点（上次讨论过的，动手前再过一遍）★
 *
 * 1. 用"浪费一个格子"的办法区分空和满：
 *      空： head == tail
 *      满： (head + 1) % N == tail
 *    代价：N 个格子只能用 N-1 个。换来的是判断极简、不需要额外变量。
 *
 * 2. 为什么满了要"丢弃并返回错误"，不能"覆盖最老的"？
 *    中断里**不能等**。覆盖式丢数据是**静默**的 —— 你永远不知道丢了。
 *    返回 1 让上层能看见、能统计。
 *
 * 3. 为什么这样写不需要加锁？
 *    head 只有写的人（中断）改，tail 只有读的人（主循环）改。
 *    **每个变量只有一个写者** → 不存在"两个人同时改同一个变量"的竞争。
 *    加 volatile 就够了（防止编译器把它优化进寄存器）。
 *    这就是 Linux 内核 kfifo 在单生产者单消费者下能无锁工作的原因。
 *
 * 4. N 取 2 的幂（64），就能用 & (N-1) 代替 % N —— 除法/取模在单片机上很慢。
 *
 * ★ 头文件只依赖 <stdint.h>，不依赖 HAL —— 这样在 PC 上也能直接编译测试。
 ******************************************************************************
 */
#ifndef __RINGBUF_H
#define __RINGBUF_H

#include <stdint.h>

#define RB_SIZE     64                  /* 必须是 2 的幂 */
#define RB_MASK     (RB_SIZE - 1)

/* 清空缓冲（上电 / 出错后复位用） */
void RB_Init(void);

/* 存 1 个字节
 * 返回 0 = 成功，1 = 已满（这个字节被丢弃） */
uint8_t RB_Put(uint8_t b);

/* 取 1 个字节
 * 返回 0 = 成功（*b 有效），1 = 空（*b 不被修改） */
uint8_t RB_Get(uint8_t *b);

/* 当前存了多少个字节（0 ~ RB_SIZE-1） */
uint16_t RB_Count(void);

#endif /* __RINGBUF_H */
