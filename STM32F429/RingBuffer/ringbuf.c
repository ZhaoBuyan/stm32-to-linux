#include "ringbuf.h"

/* 缓冲区本体 + 两个指针。
 *
 * head：下一个要【写】的位置（只有中断改）
 * tail：下一个要【读】的位置（只有主循环改）
 *
 * 两个都加 volatile：它们会被中断和主循环共同看到，
 * 不加的话编译器可能把值缓存进寄存器，主循环永远读到旧值。
 */
static volatile uint8_t  s_buf[RB_SIZE];
static volatile uint16_t s_head;
static volatile uint16_t s_tail;

void RB_Init(void)
{
    s_head = 0;
    s_tail = 0;
}

/* ============================================================================
 * ★ TODO 1：存一个字节
 *
 * 伪代码：
 *     下一个 head 位置 = (s_head + 1) & RB_MASK;      // & 代替 %
 *     if (下一个 head 位置 == s_tail) {
 *         return 1;                                   // 满了：丢掉这个字节
 *     }
 *     s_buf[s_head] = b;
 *     s_head = 下一个 head 位置;
 *     return 0;
 *
 * 注意顺序：**先算出"写完之后 head 会在哪"，判断满，再真的写、再移动**。
 * 顺序写反了会丢掉最后一个可用格子，或者写出界。
 * ========================================================================== */
uint8_t RB_Put(uint8_t b)
{
    /* TODO 1 */
    uint16_t next;
    next = (s_head + 1) & RB_MASK;
    if (next == s_tail){
        return 1;
    }
    s_buf[s_head] = b;
    s_head = next;
    return 0;
    
}

/* ============================================================================
 * ★ TODO 2：取一个字节
 *
 * 伪代码：
 *     if (s_head == s_tail) {
 *         return 1;                                   // 空：*b 不许动
 *     }
 *     *b = s_buf[s_tail];
 *     s_tail = (s_tail + 1) & RB_MASK;
 *     return 0;
 *
 * 注意：空的时候**绝对不能写 *b**，也不能动 s_tail。
 * 这种"失败时不留副作用"的写法很重要 —— 调用方不用先判断再取。
 * ========================================================================== */
uint8_t RB_Get(uint8_t *b)
{
    /* TODO 2 */
    if (s_head == s_tail) {
        return 1;
    }
    *b = s_buf[s_tail];
    s_tail = (s_tail + 1) & RB_MASK;
    return 0;
}

/* ============================================================================
 * ★ TODO 3：当前存了多少
 *
 * 提示：数是 (head - tail)，但两个都是循环索引，head 可能比 tail 小。
 *   - 直接 head - tail 会得到一个巨大的数（无符号回绕）
 *   - 所以要和 RB_MASK 与一下：  (s_head - s_tail) & RB_MASK
 *
 * 想一想：为什么这里 & RB_MASK 就等价于"取模"？
 *   因为 RB_SIZE 是 2 的幂，而 head/tail 都在 0~RB_SIZE-1 之间 —— 这跟
 *   "无符号相减自动回绕"是同一个道理。
 * ========================================================================== */
uint16_t RB_Count(void)
{
    /* TODO 3 */
    return (s_head - s_tail) & RB_MASK;
}
